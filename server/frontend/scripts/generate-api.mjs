import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const repository = new URL('../../..', import.meta.url);
const output = new URL('../src/api/schema.ts', import.meta.url);
const document = JSON.parse(execFileSync('go', ['run', './server/cmd/agentuse-openapi'], {
  cwd: repository,
  encoding: 'utf8',
}));
const ast = await openapiTS(document, {
  alphabetize: true,
  transform: schema => schema.format === 'binary' ? ts.factory.createTypeReferenceNode('Blob') : undefined,
});
const generated = '// Generated by npm run api:generate from the Server OpenAPI document.\n' + astToString(ast);

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    console.error('Server API types are out of date. Run npm run api:generate in server/frontend.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, generated);
}
